func TestRender_InstalledAppsAndEnigmaConfig(t *testing.T) {
	out := Render(demoConfig(), nil, Lazy)

	if !strings.Contains(out, "class _ConfigModule:\n") {
		t.Fatalf("missing _ConfigModule class:\n%s", out)
	}
	if !strings.Contains(out, "class _EnigmaConfig:\n") {
		t.Fatalf("missing _EnigmaConfig class:\n%s", out)
	}
	if !strings.Contains(out, `    "modules.core",`+"\n") {
		t.Fatalf("missing standalone module's INSTALLED_APPS entry:\n%s", out)
	}
	if !strings.Contains(out, `    "modules.hr.core",`+"\n") {
		t.Fatalf("missing submodule's INSTALLED_APPS entry:\n%s", out)
	}
	if !strings.Contains(out, `    "modules.hr.roster",`+"\n") {
		t.Fatalf("missing second submodule's INSTALLED_APPS entry:\n%s", out)
	}
	if strings.Contains(out, `"modules.hr",`) {
		t.Fatalf("non-standalone module must not get its own bare INSTALLED_APPS entry:\n%s", out)
	}
	if !strings.Contains(out, `"core": _ConfigModule("core", submodules={`) {
		t.Fatalf("missing core module's ENIGMA_CONFIG entry:\n%s", out)
	}
	if !strings.Contains(out, `"hr": _ConfigModule("hr", submodules={`) {
		t.Fatalf("missing hr module's ENIGMA_CONFIG entry:\n%s", out)
	}
	if !strings.Contains(out, `"core": _ConfigModule("core", submodules={}),`) {
		t.Fatalf("missing hr.core submodule's ENIGMA_CONFIG entry:\n%s", out)
	}
	if !strings.Contains(out, `"roster": _ConfigModule("roster", submodules={}),`) {
		t.Fatalf("missing hr.roster submodule's ENIGMA_CONFIG entry:\n%s", out)
	}
}
